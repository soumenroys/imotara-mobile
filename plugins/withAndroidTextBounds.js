const { withDangerousMod } = require('@expo/config-plugins');
const fs = require('fs');
const path = require('path');

const STYLE = 'ImotaraTextView';
const PLATFORM_PARENT = '@android:style/Widget.Material.TextView';

// Stops Android 15+ from cutting the last word off short Indian-script text.
//
// THE PROBLEM (seen 25 Oct 2026 on a Pixel Tablet emulator, Android 16, 1.6.0)
// The Bengali chip sends "মন খারাপ লাগছে". The bubble showed "মন খারাপ" and,
// under it, the top sliver of a second line — "লাগছে" was gone. uiautomator
// read the full string in a TextView 166 x 36 px: sized for ONE line.
//
// WHY
// From targetSdk 35 Android turns on USE_BOUNDS_FOR_WIDTH (change 63938206):
// TextView breaks lines using glyph BOUNDS. React Native measures with
// Layout.getDesiredWidth — glyph ADVANCES (TextLayoutManager.createLayout).
// Indic glyphs overhang their advances, so the drawn line no longer fits the
// width RN measured; the last word wraps onto a line the measured height has
// no room for, and the view clips it. Latin text has ~no overhang, which is
// why English bubbles never showed it. A bubble that shrink-wraps its text is
// the worst case, but any line that ends near the edge can lose a line.
//
// THE FIX
// Give every TextView the pre-35 behaviour — the one RN measures for — via
// the theme's textViewStyle, only where the attribute exists (values-v35).
// `am compat disable` cannot test this on a release build (refused above the
// change's threshold), so it was proven by building it: same 166 px box, all
// three words on one line. EditText uses editTextStyle and is not touched.
//
// WHY A PLUGIN: android/ is gitignored and regenerated by prebuild — same
// reasoning as withAndroidImeInsets / withAndroidRawSounds.
//
// ▶️ Remove when React Native measures with bounds itself (check
// TextLayoutManager for setUseBoundsForWidth on each RN upgrade).

/** Points AppTheme's textViewStyle at our style and declares its API<35 form. */
function transformStyles(xml) {
  let out = xml;
  if (!out.includes('name="android:textViewStyle"')) {
    out = out.replace(
      /(<style name="AppTheme"[^>]*>)/,
      `$1\n    <item name="android:textViewStyle">@style/${STYLE}</item>`
    );
  }
  if (!out.includes(`<style name="${STYLE}"`)) {
    out = out.replace(
      '</resources>',
      `  <style name="${STYLE}" parent="${PLATFORM_PARENT}"/>\n</resources>`
    );
  }
  if (!out.includes(`@style/${STYLE}`)) {
    throw new Error('withAndroidTextBounds: no AppTheme in styles.xml to attach textViewStyle to');
  }
  return out;
}

const V35_STYLES = `<resources>
  <style name="${STYLE}" parent="${PLATFORM_PARENT}">
    <item name="android:useBoundsForWidth">false</item>
  </style>
</resources>
`;

const withAndroidTextBounds = (config) =>
  withDangerousMod(config, [
    'android',
    (cfg) => {
      const res = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res');
      const styles = path.join(res, 'values', 'styles.xml');
      fs.writeFileSync(styles, transformStyles(fs.readFileSync(styles, 'utf8')));
      fs.mkdirSync(path.join(res, 'values-v35'), { recursive: true });
      fs.writeFileSync(path.join(res, 'values-v35', 'styles.xml'), V35_STYLES);
      return cfg;
    },
  ]);

module.exports = withAndroidTextBounds;
module.exports.transformStyles = transformStyles;
module.exports.V35_STYLES = V35_STYLES;
