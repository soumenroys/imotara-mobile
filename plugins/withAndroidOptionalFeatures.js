const { withAndroidManifest } = require('expo/config-plugins');

// Marks hardware features Imotara does NOT need as optional (required="false").
//
// THE PROBLEM THIS EXISTS FOR (21 Nov 2026, release 1.7.1)
// Play Console's pre-review check refused to send 1.7.1 for review:
//   "Required hardware feature declarations are restricting your app's
//    availability: android.hardware.screen.portrait, android.hardware.wifi"
// and its "Proceed anyway" failed with "unexpected error (5748C92F)".
//
// Imotara never declares either feature. Play INFERS them from the merged
// manifest of our libraries:
//   - ACCESS_WIFI_STATE (pulled in by a library — "picking images from camera")
//     ⇒ Play implies <uses-feature android.hardware.wifi required="true">
//   - ML Kit's GmsBarcodeScanningDelegateActivity is screenOrientation="portrait"
//     ⇒ Play implies <uses-feature android.hardware.screen.portrait required="true">
//
// THE FIX (Android's documented way to override an implied feature)
// Declare the feature explicitly with required="false". The permission and the
// activity stay exactly as they are, so nothing the app does changes — only the
// device filter on Play widens.
//
// WHY A PLUGIN: android/ is regenerated by prebuild; hand edits do not survive.
// iOS IS NOT TOUCHED.

const OPTIONAL_FEATURES = ['android.hardware.wifi', 'android.hardware.screen.portrait'];

/** Pure transform on the parsed manifest (xml2js shape) — exported for tests. */
function addOptionalFeatures(manifest) {
  if (!manifest || !manifest.manifest) {
    throw new Error('withAndroidOptionalFeatures: no <manifest> root — prebuild output changed');
  }
  const root = manifest.manifest;
  if (!Array.isArray(root['uses-feature'])) root['uses-feature'] = [];
  for (const name of OPTIONAL_FEATURES) {
    const existing = root['uses-feature'].find((f) => f && f.$ && f.$['android:name'] === name);
    if (existing) {
      existing.$['android:required'] = 'false';
    } else {
      root['uses-feature'].push({ $: { 'android:name': name, 'android:required': 'false' } });
    }
  }
  return manifest;
}

const withAndroidOptionalFeatures = (config) =>
  withAndroidManifest(config, (cfg) => {
    cfg.modResults = addOptionalFeatures(cfg.modResults);
    return cfg;
  });

module.exports = withAndroidOptionalFeatures;
module.exports.addOptionalFeatures = addOptionalFeatures;
module.exports.OPTIONAL_FEATURES = OPTIONAL_FEATURES;
